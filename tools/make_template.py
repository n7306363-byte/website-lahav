#!/usr/bin/env python3
"""One-time helper: turns the hand-written index.html into template.html + content.json.
After this, index.html is generated by lib/render.js (node tools/build.js)."""
import re, json, sys, io
src = sys.argv[1] if len(sys.argv) > 1 else 'index.html'
s = open(src, encoding='utf-8').read()
content = {}

def one(pattern, repl, count=1, flags=re.S):
    """regex replace with an exact expected number of matches"""
    global s
    n = len(re.findall(pattern, s, flags))
    assert n == count, (n, count, pattern[:90])
    s = re.sub(pattern, repl, s, flags=flags)

def grab(pattern, group=1, flags=re.S):
    m = re.search(pattern, s, flags)
    assert m, pattern[:90]
    return m.group(group)

def unesc(t):
    return t  # source text is already plain (no entities in the editable strings)

# ------------------------------------------------------------------ simple texts (desktop + mobile)
hero_sub   = grab(r'transform-origin:100% 50%;">([^<]+)</p>')
hero_t1    = grab(r'transform-origin:100% 0;">(הופכים חלומות)</p>')
hero_t2    = grab(r'transform-origin:100% 0;">(למציאות)</p>')
hero_text  = grab(r'text-shadow:0 0 18px rgba\(10,47,35,\.7\);">([^<]+)</p>')
content['hero'] = {'sub': hero_sub, 'title1': hero_t1, 'title2': hero_t2, 'text': hero_text}
one(r'(transform-origin:100% 50%;">)[^<]+(</p>)', r'\1{{t:hero.sub}}\2')
one(r'(transform-origin:100% 0;">)הופכים חלומות(</p>)', r'\1{{t:hero.title1}}\2')
one(r'(transform-origin:100% 0;">)למציאות(</p>)', r'\1{{t:hero.title2}}\2')
one(r'(text-shadow:0 0 18px rgba\(10,47,35,\.7\);">)[^<]+(</p>)', r'\1{{t:hero.text}}\2')
one(r'(lh-m-hsub font-liebling-light">)[^<]+(</p>)', r'\1{{t:hero.sub}}\2')
one(r'(lh-m-h1a font-liebling">)[^<]+(</h1>)', r'\1{{t:hero.title1}}\2')
one(r'(lh-m-h1b font-liebling" aria-hidden="true">)[^<]+(</p>)', r'\1{{t:hero.title2}}\2')
one(r'(lh-m-hp font-liebling-light">)[^<]+(</p>)', r'\1{{t:hero.text}}\2')

# story
story_label = grab(r'text-transform:uppercase;">(OUR STORY)</p>')
story_title = grab(r'font-size:48px; line-height:normal;">(הסיפור שלנו)</h2>')
d_body = re.search(r'(  <div class="font-liebling-light absolute text-right" style="left:139px; top:1595px; width:727px; font-size:18px; line-height:24px;">\n)(.*?)(  </div>\n)', s, re.S)
paras = re.findall(r'<p(?: class="mb-0")?>([^<]*)</p>', d_body.group(2))
assert len(paras) == 4, paras
content['story'] = {'label': story_label, 'title': story_title, 'paragraphs': paras}
one(r'(text-transform:uppercase;">)OUR STORY(</p>)', r'\1{{t:story.label}}\2')
one(r'(font-size:48px; line-height:normal;">)הסיפור שלנו(</h2>)', r'\1{{t:story.title}}\2')
one(r'(lh-m-label font-storyscript">)OUR STORY(</p>)', r'\1{{t:story.label}}\2')
one(r'(lh-m-h2s font-liebling">)הסיפור שלנו(</h2>)', r'\1{{t:story.title}}\2')
s = s.replace(d_body.group(0), d_body.group(1) +
  '{{#each story.paragraphs as p}}    <p{{#if @last}}{{else}} class="mb-0"{{/if}}>{{t:p}}</p>\n{{/each}}' + d_body.group(3))
m_body = re.search(r'(        <div class="lh-m-body font-liebling-light">\n)(.*?)(        </div>\n)', s, re.S)
assert len(re.findall(r'<p>', m_body.group(2))) == 4
s = s.replace(m_body.group(0), m_body.group(1) +
  '{{#each story.paragraphs as p}}          <p>{{t:p}}</p>\n{{/each}}' + m_body.group(3))

# projects heading
content['projectsSection'] = {'label': 'Projects', 'title': 'פרוייקטים', 'more': ''}
one(r'(color:var\(--gold\);">)Projects(</p>)', r'\1{{t:projectsSection.label}}\2')
one(r'(font-size:55px; line-height:normal;">)פרוייקטים(</h2>)', r'\1{{t:projectsSection.title}}\2')
one(r'(lh-m-label font-storyscript">)Projects(</p>)', r'\1{{t:projectsSection.label}}\2')
one(r'(<h2 class="font-liebling-light">)פרוייקטים(</h2>)', r'\1{{t:projectsSection.title}}\2')

# vision
vision_text = grab(r'font-size:40px; line-height:55px;">([^<]+)</p>')
content['vision'] = {'label': 'OUR VISON', 'title': 'החזון שלנו', 'text': vision_text}
one(r'(color:var\(--gold\);">)OUR VISON(</span>)', r'\1{{t:vision.label}}\2')
one(r'(font-size:90px; line-height:62px;">)החזון שלנו(</h2>)', r'\1{{t:vision.title}}\2')
one(r'(font-size:40px; line-height:55px;">)[^<]+(</p>)', r'\1{{t:vision.text}}\2')
one(r'(lh-m-vlabel font-storyscript">)OUR VISON(</p>)', r'\1{{t:vision.label}}\2')
one(r'(lh-m-vh2 font-liebling-bold">)החזון שלנו(</h2>)', r'\1{{t:vision.title}}\2')
one(r'(lh-m-vp font-liebling-light">)[^<]+(</p>)', r'\1{{t:vision.text}}\2')

# services heading
content['servicesSection'] = {'label': 'what we do', 'title': 'מה אנחנו עושים'}
one(r'(color:var\(--gold\);">)what we do(</p>)', r'\1{{t:servicesSection.label}}\2')
one(r'(font-size:48px; line-height:normal;">)מה אנחנו עושים(</h2>)', r'\1{{t:servicesSection.title}}\2')
one(r'(style="text-align:center;">)what we do(</p>)', r'\1{{t:servicesSection.label}}\2')
one(r'(<h2 class="font-liebling">)מה אנחנו עושים(</h2>)', r'\1{{t:servicesSection.title}}\2')

# testimonials heading
content['testimonialsSection'] = {'label': 'testimonials', 'title': 'לקוחות שלנו ממליצים'}
one(r'(color:var\(--gold\);">)testimonials(</p>)', r'\1{{t:testimonialsSection.label}}\2')
one(r'(text-align:center;">)לקוחות שלנו ממליצים(</h2>)', r'\1{{t:testimonialsSection.title}}\2')
one(r'(lh-m-label font-storyscript">)testimonials(</p>)', r'\1{{t:testimonialsSection.label}}\2')
one(r'(<h2 class="font-liebling">)לקוחות שלנו ממליצים(</h2>)', r'\1{{t:testimonialsSection.title}}\2')

# ------------------------------------------------------------------ services (desktop + mobile blocks)
svc_titles = re.findall(r'<div class="svc-item__label font-liebling">([^<]+)</div>', s)
svc_imgs   = re.findall(r'<img class="svc-item__img" src="([^"]+)"', s)
svc_bgs    = re.findall(r'<div class="svc-bg__img" style="background-image:url\(([^)]+)\);"', s)
svc_m_imgs = re.findall(r'<div class="lh-m-sitem"><img src="([^"]+)"', s)
colors = re.search(r'var CARD_RGB = \[\[(\d+), (\d+), (\d+)\], \[(\d+), (\d+), (\d+)\], \[(\d+), (\d+), (\d+)\]\];', s)
cols = ['#%02x%02x%02x' % tuple(int(colors.group(i)) for i in range(3*k+1, 3*k+4)) for k in range(3)]
assert len(svc_titles) == 3 and len(svc_imgs) == 3 and len(svc_bgs) == 3 and len(svc_m_imgs) == 3
content['services'] = [{'title': svc_titles[i], 'image': svc_imgs[i], 'imageMobile': svc_m_imgs[i], 'bg': svc_bgs[i], 'color': cols[i]} for i in range(3)]

# desktop backgrounds
one(r'(    <div class="svc-bg" data-i="0">.*?\n    <div class="svc-bg" data-i="2">[^\n]*\n)',
    '{{#each services as v}}    <div class="svc-bg" data-i="{{@i}}"><div class="svc-bg__img" style="background-image:url({{a:v.bg}});"></div></div>\n{{/each}}')
# desktop cards
one(r'(      <div class="svc-item" data-i="0">.*?      <div class="svc-item" data-i="2">.*?\n      </div>\n)',
    '{{#each services as v}}      <div class="svc-item" data-i="{{@i}}">\n'
    '        <img class="svc-item__img" src="{{a:v.image}}" alt="{{a:v.title}}" />\n'
    '        <div class="svc-item__num font-liebling-light">{{@n}}</div>\n'
    '        <div class="svc-item__label font-liebling">{{t:v.title}}</div>\n'
    '      </div>\n{{/each}}')
# mobile stage
one(r'<div class="lh-m-sbg"><div class="lh-m-sbg__img" data-bg="images/service-bg-1.jpg"></div></div><div class="lh-m-sbg"><div class="lh-m-sbg__img" data-bg="images/service-bg-2.jpg"></div></div><div class="lh-m-sbg"><div class="lh-m-sbg__img" data-bg="images/service-bg-3.jpg"></div></div>',
    '{{#each services as v}}<div class="lh-m-sbg"><div class="lh-m-sbg__img" data-bg="{{a:v.bg}}"></div></div>{{/each}}')
one(r'<div class="lh-m-sitem"><img src="images/m-svc-1\.jpg".*?<div class="lh-m-scard__label font-liebling">בניית דקים ופרגולות</div></div>',
    '{{#each services as v}}<div class="lh-m-sitem"><img src="{{a:v.imageMobile}}" alt="{{a:v.title}}" {{#if @first}}{{else}}loading="lazy" {{/if}}decoding="async">'
    '<div class="lh-m-scard__num font-liebling-light">{{@n}}</div><div class="lh-m-scard__label font-liebling">{{t:v.title}}</div></div>{{/each}}')
# colours: first card colour also lives in two css defaults, all three in the two stepper scripts
one(r'(\.svc-card\{[^}]*?background:)#223d4f;', r'\1{{h:services.0.color}};')
one(r'(\.lh-m-scard\{[^}]*?background:)#223d4f;', r'\1{{h:services.0.color}};')
one(r'var CARD_RGB = \[\[34, 61, 79\], \[35, 84, 65\], \[96, 48, 15\]\];[^\n]*', 'var CARD_RGB = {{j:derived.rgb}};', count=2)

# ------------------------------------------------------------------ testimonials
d = re.search(r'(  <div class="absolute flex items-start" style="left:139px; top:11507px; gap:29px; direction:ltr;">\n)(.*?)(  </div>\n\n  <!-- SEAL / CTA / FOOTER -->)', s, re.S)
cards = re.findall(r'<p class="font-notosans" style="flex:1; margin:0; width:100%; font-size:16px; line-height:24px; color:#fff;">([^<]+)</p>.*?>([^<]+)</span>\s*<div class="lh-av"[^>]*><div style="[^"]*"><img src="([^"]+)"', d.group(2), re.S)
assert len(cards) == 4, len(cards)
legacy1 = 'width:51.473px' in d.group(2)
content['testimonials'] = [{'name': c[1], 'text': c[0], 'photo': c[2]} for c in cards]
content['testimonials'][0]['legacy'] = bool(legacy1)
card_tpl = ('{{#each testimonials as t}}    <div style="width:{{a:t._w}}px; height:237px; box-sizing:border-box; padding:32px; display:flex; flex-direction:column; align-items:flex-end; gap:16px; background:#0d3a2b; border:1px solid #88c064; border-radius:12px; box-shadow:0 1px 1px rgba(10,13,18,.05); direction:rtl; text-align:right;">\n'
  '      <p class="font-notosans" style="flex:1; margin:0; width:100%; font-size:16px; line-height:24px; color:#fff;">{{t:t.text}}</p>\n'
  '      <div style="display:flex; align-items:center; justify-content:flex-end; gap:8px; direction:ltr;">\n'
  '        <span class="font-notosans" style="font-size:16px; line-height:24px; font-weight:700; color:#fff; white-space:nowrap; direction:rtl;">{{t:t.name}}</span>\n'
  '        {{#if t.legacy}}<div class="lh-av" style="background:#cecece;"><div style="left:-7px; top:0; width:51.473px; height:38px;"><img src="{{a:t.photo}}" alt="" style="width:100%; height:179.89%; left:-1.5%; top:-11.99%;" /></div></div>'
  '{{else}}<div class="lh-av" style="background:#cecece;"><div style="left:0; top:0; width:37px; height:37px;"><img src="{{a:t.photo}}" alt="" style="left:0; top:0; width:100%; height:100%; object-fit:cover;{{#if t.pos}} object-position:{{a:t.pos}};{{/if}}" /></div></div>{{/if}}\n'
  '      </div>\n'
  '    </div>\n{{/each}}')
s = s.replace(d.group(0), d.group(1) + card_tpl + d.group(3))
m = re.search(r'(      <div class="lh-m-cards">)(.*?)(</div>\n    </div></section>)', s, re.S)
assert m.group(2).count('<blockquote') == 4
q_tpl = ('{{#each testimonials as t}}<blockquote class="lh-m-quote"><p class="font-notosans">{{t:t.text}}</p>'
         '<footer><img src="{{a:t.photo}}" alt="" loading="lazy" decoding="async"{{#if t.pos}} style="object-position:{{a:t.pos}};"{{/if}}><b class="font-notosans">{{t:t.name}}</b></footer></blockquote>{{/each}}')
s = s.replace(m.group(0), m.group(1) + q_tpl + m.group(3))

# ------------------------------------------------------------------ projects (script data)
pm = re.search(r'  var PROJECT_TITLE = "([^"]*)";\n  var PROJECT_MORE = "([^"]*)";\n  var PROJECT_TEXT = \[\n(.*?)\n  \];\n(.*?)  var PROJECT_THUMBS = \[([^\]]*)\];\n', s, re.S)
assert pm
title = pm.group(1); more = pm.group(2)
texts = json.loads('[' + pm.group(3) + ']')
thumbs = json.loads('[' + pm.group(5) + ']')
photos = re.findall(r'photo: "([^"]+)"', pm.group(4))
crop = re.search(r'crop: \{ l: ([-\d.]+), t: ([-\d.]+), w: ([-\d.]+), h: ([-\d.]+) \}', pm.group(4))
mphotos = re.findall(r"'(images/m-project-\d\.jpg)'", s)
assert len(photos) == 3 and len(mphotos) == 3
content['projectsSection']['more'] = more
content['projects'] = []
for i in range(3):
    pr = {'title': title, 'paragraphs': texts, 'photo': photos[i], 'photoMobile': mphotos[i], 'thumbs': thumbs}
    if i == 0 and crop:
        pr['crop'] = {'l': float(crop.group(1)), 't': float(crop.group(2)), 'w': float(crop.group(3)), 'h': float(crop.group(4))}
    content['projects'].append(pr)
s = s.replace(pm.group(0),
  '  var PROJECT_MORE = {{j:projectsSection.more}};\n'
  '  // texts and photos come from content.json (admin); rects / box positions are layout and live in lib/render.js\n'
  '  var PROJECTS = {{j:derived.projects}};\n'
  '  var PROJECT_THUMBS = {{j:derived.thumbs}};\n')
# code that consumes the data: per-project thumbnails / mobile photo
one(r"        \+ PROJECT_THUMBS\.map\(function \(t\) \{", "        + (p.thumbs || PROJECT_THUMBS).map(function (t) {")
one(r"\+ '<div class=\"lh-m-pthumbs\">' \+ PROJECT_THUMBS\.map\(function \(t\) \{", "+ '<div class=\"lh-m-pthumbs\">' + (p.thumbs || PROJECT_THUMBS).map(function (t) {")
one(r"      var PHOTOS = \[[^\]]*\];\n", "")
one(r"var photo = PHOTOS\[i\] \|\| p\.photo;", "var photo = p.photoMobile || p.photo;")

# focus point of the photo (object-position) — optional, set from the admin
one(r"(: 'left:0; top:0; width:100%; height:100%;')(;\n)", r"\1 + (p.pos ? ' object-position:' + p.pos + ';' : '')\2")
one(r"(data-photo=\"' \+ photo \+ '\" alt=\"' \+ esc\(p\.title\) \+ '\" decoding=\"async\"' \+ \(i \? ' loading=\"lazy\"' : ''\))( \+ '></div></div>';)",
    r"\1 + (p.pos ? ' style=\"object-position:' + esc(p.pos) + ';\"' : '')\2")
open('template.html', 'w', encoding='utf-8').write(s)
json.dump(content, open('content.json', 'w', encoding='utf-8'), ensure_ascii=False, indent=2)
print('template.html', len(s), 'bytes; content.json written')
